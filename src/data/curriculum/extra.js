const toExample = ([en, tr]) => ({ en, tr })
const toQuestion = ([prompt, options, answer, explain]) => ({
  prompt,
  options,
  answer,
  explain,
})

function makeTopic(level, order, spec) {
  const midpoint = Math.ceil(spec.notes.length / 2)
  const examplePoint = Math.ceil(spec.examples.length / 2)

  return {
    id: `${level}-${spec.slug}`,
    level,
    order,
    accent: spec.accent,
    title: spec.title,
    subtitle: spec.subtitle,
    summary: spec.summary,
    sections: [
      {
        heading: spec.headings?.[0] ?? 'Temel Yapı',
        subheading: spec.subheadings?.[0] ?? spec.subtitle,
        notes: spec.notes.slice(0, midpoint),
        examples: spec.examples.slice(0, examplePoint).map(toExample),
      },
      {
        heading: spec.headings?.[1] ?? 'Kullanım ve Dikkat',
        subheading: spec.subheadings?.[1] ?? 'Doğru cümle içinde kullanma',
        notes: spec.notes.slice(midpoint),
        examples: spec.examples.slice(examplePoint).map(toExample),
      },
    ],
    quiz: spec.quiz.map(toQuestion),
  }
}

function buildLevel(level, startOrder, specs) {
  return specs.map((spec, index) => makeTopic(level, startOrder + index, spec))
}

